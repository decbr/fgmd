// bundles the site's content into src/generated/content.ts, so the Worker ships with every
// markdown file inside it and needs no storage at runtime.
//
// the point of the site is that its pages are markdown and nothing else, so this script takes
// whatever .md files it finds - drop one in content/ and it is a page - plus the docs from the
// repo above, which are the same files npm and GitHub read.
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const site = resolve(here, '..');
const repo = resolve(site, '..');
const out = join(site, 'src', 'generated', 'content.ts');

// every .md under a directory, recursively, as repo-relative paths
function markdown(dir) {
	const found = [];
	for (const entry of readdirSync(dir, { withFileTypes: true })) {
		const path = join(dir, entry.name);
		if (entry.isDirectory()) found.push(...markdown(path));
		else if (entry.name.endsWith('.md')) found.push(path);
	}
	return found.sort();
}

const files = [...markdown(join(site, 'content')), ...markdown(join(repo, 'docs'))];

const sources = new Map();
for (const file of files) {
	sources.set(relative(repo, file).split(/[\\/]/).join('/'), readFileSync(file, 'utf8'));
}

const css = readFileSync(join(site, 'src', 'style.css'), 'utf8');
const cssHash = createHash('sha256').update(css).digest('hex').slice(0, 8);

const entries = [...sources].map(([path, text]) => `\t${JSON.stringify(path)}: ${JSON.stringify(text)}`).join(',\n');

mkdirSync(dirname(out), { recursive: true });
writeFileSync(
	out,
	`// generated by scripts/collect.mjs - do not edit, and do not commit\n` +
		`// ${sources.size} markdown files, collected ${new Date().toISOString()}\n\n` +
		`export const sources: Record<string, string> = {\n${entries}\n};\n\n` +
		`export const css = ${JSON.stringify(css)};\n\n` +
		`export const cssHash = ${JSON.stringify(cssHash)};\n`
);

console.log(`collected ${sources.size} markdown files and ${(css.length / 1024).toFixed(1)}kB of css`);
